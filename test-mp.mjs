// Multiplayer session checks against a running server: host handover in the lobby, rejoin after a drop, pause when every human is gone.
// usage: node test-mp.mjs ws://127.0.0.1:3000
import WebSocket from "ws";
const URL = process.argv[2], sleep = (ms) => new Promise((r) => setTimeout(r, ms));
function client(first, label) {
  const c = { ws: new WebSocket(URL), msgs: [], last: null, label };
  c.ws.on("open", () => c.ws.send(JSON.stringify(first)));
  c.ws.on("message", (d) => { const m = JSON.parse(d); if (m.t === "s") c.last = m; else c.msgs.push(m); });
  c.ws.on("close", (code) => (c.closed = code));
  c.send = (m) => c.ws.send(JSON.stringify(m)); c.get = (t) => c.msgs.filter((m) => m.t === t).at(-1); return c;
}
let ok = true; const check = (name, cond) => { console.log((cond ? "PASS " : "FAIL ") + name); ok &&= !!cond; };
// --- 2. host handover
const h = client({ t: "create", name: "Host" }); await sleep(500);
const code = h.get("lobby").code;
const g = client({ t: "join", code, name: "Guest" }); await sleep(300);
const g2 = client({ t: "join", code, name: "Third" }); await sleep(300);
h.send({ t: "addAI", diff: "easy" }); await sleep(300);
check("guest is not host", g.get("lobby").host !== g.get("lobby").you);
g.send({ t: "start" }); await sleep(300);
check("guest can't start", !g.msgs.some((m) => m.t === "start"));
h.ws.close(); await sleep(400);
const L = g.get("lobby");
check(`host handed to Guest (slots: ${L.slots.map((s) => s.name).join(",")})`, L.host === L.you && L.slots[L.host].name === "Guest");
check("Third sees Guest as host", g2.get("lobby").host === 0 && g2.get("lobby").you === 1);
g.send({ t: "addAI", diff: "easy" }); await sleep(300);
check("new host can add AI with a free name", g.get("lobby").slots.filter((s) => s.ai).map((s) => s.name).join() === "Ashford AI,Brennmark AI");
g.send({ t: "start" }); await sleep(800);
check("new host starts the game", g.get("start")?.me === 0 && g2.get("start")?.me === 1);
// --- 1. rejoin
const tok = g2.get("session"); await sleep(1000);
g2.ws.close(); await sleep(400);
check("others told about the drop", g.msgs.some((m) => m.t === "notice" && /Third lost connection/.test(m.msg)));
await sleep(3000);
const back = client({ t: "rejoin", code: tok.code, token: tok.token }); await sleep(800);
check("rejoin gets map + same seat", back.msgs.some((m) => m.t === "map") && back.get("start")?.me === 1 && back.last?.me === 1);
check("still alive after rejoin", back.last?.players[1].alive);
check("others told player is back", g.msgs.some((m) => m.t === "notice" && /Third is back/.test(m.msg)));
const bad = client({ t: "rejoin", code: tok.code, token: "nope" }); await sleep(400);
check("wrong token refused", bad.msgs[0]?.rejoin === false);
const tab2 = client({ t: "rejoin", code: tok.code, token: tok.token }); await sleep(600);
check("second tab takes over, first closed with 4000", back.closed === 4000 && tab2.get("start")?.me === 1);
// --- pause when every human is gone (single player)
const sp = client({ t: "single", name: "Solo", ais: 1 }); await sleep(1500);
const st = sp.get("session"), t0 = sp.last.tick; sp.ws.close(); await sleep(3000);
const sp2 = client({ t: "rejoin", code: st.code, token: st.token }); await sleep(600);
check(`single player paused while away (tick ${t0} -> ${sp2.last?.tick})`, sp2.last && sp2.last.tick - t0 < 15);
// --- 4. public lobby list, 5. teams, 9. chat + pings
const HTTP = URL.replace(/^ws/, "http");
const pubH = client({ t: "create", name: "Pub", public: false }); await sleep(500);
const pc = pubH.get("lobby").code;
const listed = async () => (await (await fetch(HTTP + "/api/lobbies")).json()).some((l) => l.code === pc);
check("private game not listed", !(await listed()));
pubH.send({ t: "public", on: true }); await sleep(300);
check("public game listed", await listed());
const p2 = client({ t: "join", code: pc, name: "Mate" }); await sleep(300);
check("joiner starts on own team", p2.get("lobby").slots.map((s) => s.team).join() === "0,1");
p2.send({ t: "team", slot: 0, team: 1 }); await sleep(300);
check("player can't change someone else's team", pubH.get("lobby").slots[0].team === 0);
p2.send({ t: "team", slot: 1, team: 0 }); await sleep(300);
check("player joins host's team", pubH.get("lobby").slots[1].team === 0);
pubH.send({ t: "start" }); await sleep(300);
check("start refused with one team", !pubH.get("start") && /same team/.test(pubH.get("error")?.msg));
pubH.send({ t: "addAI", diff: "easy" }); await sleep(300);
check("AI gets a free team", pubH.get("lobby").slots[2].team === 1);
p2.send({ t: "chat", text: "hello lobby" }); await sleep(300);
check("lobby chat reaches host", pubH.get("chat")?.text === "hello lobby" && pubH.get("chat")?.from === "Mate");
pubH.send({ t: "start" }); await sleep(800);
check("2v1 game started, now listed as live (to watch, not join)", pubH.get("start") && (await (await fetch(HTTP + "/api/lobbies")).json()).find((l) => l.code === pc)?.live === true);
await sleep(300);
check("snapshot carries teams", pubH.last?.players.map((p) => p.team).join() === "0,0,1");
p2.send({ t: "chat", text: "team only", team: true }); p2.send({ t: "mark", x: 40, y: 41 }); await sleep(400);
check("team chat + ping reach ally", pubH.msgs.some((m) => m.t === "chat" && m.team && m.text === "team only") && pubH.get("mark")?.x === 40);
p2.send({ t: "chat", text: "<b>x</b>\u0007" }); await sleep(300);
check("chat text passed as data, control chars stripped", pubH.get("chat")?.text === "<b>x</b>");
// --- maps + live spectating
const mh = client({ t: "create", name: "Mapper", public: true, map: "river" }); await sleep(500);
check("lobby remembers the chosen map", mh.get("lobby").map === "river");
const mc = mh.get("lobby").code, mg = client({ t: "join", code: mc, name: "Mguest" }); await sleep(300);
mg.send({ t: "map", map: "plains" }); await sleep(200);
check("only the host can change the map", mh.get("lobby").map === "river");
mh.send({ t: "map", map: "forest" }); await sleep(300);
check("host changes the map, guest sees it", mg.get("lobby").map === "forest");
mh.send({ t: "start" }); await sleep(800);
check("game starts on that map", mh.get("map")?.map === "forest" && mg.get("map")?.map === "forest");
const late = client({ t: "join", code: mc, name: "Late" }); await sleep(300);
check("joining a running game suggests watching", late.get("error")?.started === true);
const liveL = (await (await fetch(HTTP + "/api/lobbies")).json()).find((l) => l.code === mc);
check("running public game listed as live", liveL?.live === true && liveL.map === "forest");
const spec = client({ t: "spectate", code: mc, name: "Viewer" }); await sleep(800);
check("spectator gets the map and sees everything", spec.get("start")?.me === -1 && spec.get("start")?.live && spec.last?.me === -1 && spec.last.ents.some((e) => e[2] === 0) && spec.last.ents.some((e) => e[2] === 1));
check("players told someone is watching", mh.msgs.some((m) => m.t === "notice" && /Viewer is watching/.test(m.msg)));
const tk = spec.last.tick; spec.send({ t: "speed", speed: 8 }); await sleep(1000);
check(`spectator can't speed up a live game (${spec.last.tick - tk} ticks in 1 s)`, spec.last.tick - tk < 15);
const vill = mh.last.ents.find((e) => e[2] === 0 && e[1] === mh.get("map").kinds.indexOf("villager"));
spec.send({ t: "cmd", c: { t: "move", ids: [vill[0]], x: 70, y: 70 } }); await sleep(600);
const v2 = mh.last.ents.find((e) => e[0] === vill[0]);
check("spectator can't give orders", v2 && Math.abs(v2[3] - vill[3]) < 50 && Math.abs(v2[4] - vill[4]) < 50);
spec.send({ t: "chat", text: "gg" }); await sleep(300);
check("spectator chat reaches players", mh.get("chat")?.from === "Viewer (watching)" && mh.get("chat")?.text === "gg");
mg.send({ t: "chat", text: "team secret", team: true }); await sleep(300);
check("team chat hidden from spectators", !spec.msgs.some((m) => m.t === "chat" && m.text === "team secret"));
const sp3 = client({ t: "spectate", code: "ZZZZ", name: "X" }); await sleep(300);
check("unknown code refused", /No running game/.test(sp3.get("error")?.msg ?? ""));
process.exit(ok ? 0 : 1);
